@app.post("/vault/ingest-mixed", status_code=status.HTTP_202_ACCEPTED)
async def ingest_mixed_files(
    request: Request,
    background_tasks: BackgroundTasks,
    db: Annotated[Session, Depends(get_db)],
    files: list[UploadFile] = File(...),
    chunk_size: int = 1000,
    chunk_overlap: int = 200,
):
    """
    Accepts large files or ZIP archives, saves them to disk while monitoring disconnections,
    and forwards chunk_size and chunk_overlap to the background parsing job.
    """
    supported_formats = (".pdf", ".docx", ".xlsx", ".pptx", ".csv", ".md", ".txt")
    queued_files = []
    file_names = ",".join([file.filename for file in files])
    job = IngestionJob(uploaded_files=file_names, status="submitted")
    db.add(job)
    db.commit()
    db.refresh(job)
    job_id = int(job.job_id)
    file_batch = []
    try:
        for file in files:
            file_ext = os.path.splitext(file.filename)[-1].lower()
            if file_ext not in supported_formats and file_ext != ".zip":
                job.status = "failed"
                job.error_message = f"Unsupported file format: {file.filename}"
                db.commit()
                raise HTTPException(
                    status_code=400, detail=f"Unsupported format: '{file.filename}'"
                )
            temp_file_id = f"{uuid.uuid4()}_{file.filename}"
            temp_path = os.path.join(settings.TEMP_UPLOAD_DIR, temp_file_id)

            try:
                # Stream disk writes (Phase 1)
                with open(temp_path, "wb") as buffer:
                    while chunk := await file.read(1024 * 1024):  # 1MB blocks
                        if await request.is_disconnected():
                            logger.warning(
                                f"Client disconnected during upload of {file.filename}"
                            )
                            buffer.close()
                            if os.path.exists(temp_path):
                                os.remove(temp_path)

                            # Update job as failed in DB
                            job.status = "failed"
                            job.error_message = (
                                f"Client disconnected during {file.filename} upload."
                            )
                            db.commit()

                            return {
                                "status": "Aborted",
                                "message": f"Client disconnected during {file.filename} upload.",
                            }
                        buffer.write(chunk)
                file_batch.append({"path": temp_path, "filename": file.filename})
            except Exception as e:
                if os.path.exists(temp_path):
                    os.remove(temp_path)

                # Update job as failed in DB
                job.status = "failed"
                job.error_message = str(e)
                db.commit()
                raise e

            # UPDATE JOB STATUS TO 'PROCESSING' ON FIRST VALID FILE

            job.status = "processing"
            job.step = f"Processing {len(file_batch)} file(s)"
            job.progress = 10
            db.commit()
            # Queue ONE background task for the entire batch
            background_tasks.add_task(
                process_batch_ingestion,
                job_id,
                file_batch,
                chunk_size,
                chunk_overlap,
            )
        return {
            "job_id": job_id,
            "status": "Processing",
            "message": f"{len(queued_files)} file(s) accepted for background ingestion.",
            "files": queued_files,
            "config": {"chunk_size": chunk_size, "chunk_overlap": chunk_overlap},
        }
    except Exception as e:
        logger.error(f"Error during agent execution: {e!s}")
        raise HTTPException(status_code=500, detail=f"Agent Execution Failed: {e!s}")
    # finally:
    #     # Safely close DB connection at the very end of the endpoint handler
    #     db.close()


@app.post("/vault/chat")
async def chat_with_agent(payload: AgentChatRequest):
    system_prompt = SystemMessage(
        content=(
            "You are an AI data analyst assistant. "
            "When asked to query, analyze, or summarize database tables, YOU MUST USE the available tools "
            "(e.g., query_tabular_database) to fetch the required data. "
            "Do NOT output your internal thoughts or guess data values. "
            "Always format your final response cleanly in Markdown (use Markdown tables for structured data)."
        )
    )

    langgraph_messages = [system_prompt]

    for m in payload.messages:
        if m.content and m.content.strip():
            if m.role == "user":
                langgraph_messages.append(HumanMessage(content=m.content))
            else:
                langgraph_messages.append(AIMessage(content=m.content))

    if len(langgraph_messages) <= 1:
        raise HTTPException(status_code=400, detail="No valid user message provided.")

    node_holder: list[dict[str, Any]] = []
    agent_config = {
        "configurable": {
            "db_manager": db_engine,
            "retrieval_limit": payload.retrieval_k,
            "ollama_base_url": ollama_base_url,
            "temperature": payload.temperature,
            "top_k": payload.top_k,
            "shared_node_container": node_holder,
        }
    }

    async def event_generator():
        try:
            # Stream events using 'updates' or 'messages' mode
            async for event in agent_app.astream_events(
                {"messages": langgraph_messages}, config=agent_config, version="v2"
            ):
                kind = event["event"]

                # Yield LLM streamed content tokens in real-time
                if kind == "on_chat_model_stream":
                    chunk_text = event["data"]["chunk"].content
                    if chunk_text:
                        # Output Server-Sent Events or plain JSON lines
                        yield f"data: {json.dumps({'type': 'content', 'delta': chunk_text})}\n\n"

            # Send inspect_nodes metadata block after execution finishes
            if node_holder:
                yield f"data: {json.dumps({'type': 'inspected_nodes', 'nodes': node_holder})}\n\n"

            yield "data: [DONE]\n\n"

        except Exception as e:
            logger.error(f"Error during agent streaming: {e!s}")
            yield f"data: {json.dumps({'type': 'error', 'content': str(e)})}\n\n"

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",  # Prevents Nginx/proxy response buffering
        },
    )


@app.post("/vault/clear", status_code=status.HTTP_200_OK)
async def clear_database():
    """Wipes the SQLite database and flushes cached files."""
    try:
        db_engine.wipe_all_data()
        tabular_db_path = settings.DATABASE_URL
        if os.path.exists(tabular_db_path):
            os.remove(tabular_db_path)
        parser_engine.wipe_all_images_and_tables()
        db_engine.init_db()
        return {
            "status": "Success",
            "message": "All database and tabular states cleared successfully.",
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to clear database: {e!s}")


@app.get(
    "/job/status/job_id", response_model=JobResponse, status_code=status.HTTP_200_OK
)
async def get_job_status_by_id(job_id: int, db: Annotated[Session, Depends(get_db)]):
    job = db.query(IngestionJob).filter(IngestionJob.job_id == job_id).first()
    if not job:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Job with ID {job_id} not found.",
        )

    return job


