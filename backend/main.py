def clean_tool_artifacts(text: str) -> str:
    if not text:
        return ""

    # 1. Remove "| Tool Outputs Begin | ... | Tool Outputs End |" block markers
    text = re.sub(
        r"\|?\s*Tool Outputs (Begin|End)\s*\|?", "", text, flags=re.IGNORECASE
    )

    # 2. Remove Chunk metadata headers (e.g., [Source File: ... | Chunk ID: ...])
    text = re.sub(r"\[?Source File:.*?Chunk ID:.*?\]?", "", text, flags=re.IGNORECASE)

    # 3. Clean up markdown table separators left behind (|---|---|)
    text = re.sub(r"\|[\s\-:]*\|", "", text)

    # 4. Collapse leftover double pipes or leading/trailing whitespace
    text = re.sub(r"\|+", " ", text)

    return text.strip()


def clean_deepseek_response(text: str) -> str:
    """Removes complete, orphan, and unclosed <think>...</think> monologue blocks

    from DeepSeek model output.
    """
    if not text:
        return ""

    # 1. Remove closed <think>...</think> blocks
    cleaned = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL)

    # 2. Handle unclosed <think> tags (if model cut off mid-thought due to max tokens)
    cleaned = re.sub(r"<think>.*$", "", cleaned, flags=re.DOTALL)

    # 3. Handle orphan </think> tags (removes everything before and including </think>)
    if "</think>" in cleaned:
        cleaned = cleaned.split("</think>", 1)[-1]

    # 4. Clean up leading stray brackets, trailing artifacts, and whitespace
    cleaned = re.sub(r"^[\]\)\s]+", "", cleaned).strip()

    return cleaned


def extract_final_agent_response(final_state: dict[str, Any]) -> str:
    """Extracts the final AI message from LangGraph state and strips thinking artifacts."""
    if not final_state or "messages" not in final_state:
        return "No response generated by the agent."

    messages = final_state["messages"]
    raw_content = ""

    # Locate the last non-empty AI Message
    for msg in reversed(messages):
        if isinstance(msg, ToolMessage):
            continue
        if isinstance(msg, AIMessage):
            # Skip messages that are exclusively tool call requests without text
            if (
                getattr(msg, "tool_calls", None)
                and not _extract_text_content(msg.content).strip()
            ):
                continue

            raw_content = _extract_text_content(msg.content)
            if raw_content.strip():
                break

    # Fallback to last message in thread if no valid AIMessage content was matched
    if not raw_content and messages:
        last_msg = messages[-1]
        raw_content = _extract_text_content(getattr(last_msg, "content", str(last_msg)))

    cleaned = clean_deepseek_response(raw_content)
    cleaned = clean_tool_artifacts(cleaned)

    return cleaned if cleaned else raw_content.strip()


def _extract_text_content(content: Any) -> str:
    """Helper to safely coerce string or list-based LangChain message content to a string."""
    if isinstance(content, str):
        return content
    elif isinstance(content, list):
        # Handle structured content blocks: [{"type": "text", "text": "..."}]
        parts = []
        for block in content:
            if isinstance(block, str):
                parts.append(block)
            elif isinstance(block, dict) and block.get("type") == "text":
                parts.append(block.get("text", ""))
        return "".join(parts)
    return str(content) if content else ""


def process_batch_ingestion(
    job_id: int,
    file_batch: list[dict],
    chunk_size: int,
    chunk_overlap: int,
):
    db = SessionLocal()
    failed_files = []

    try:
        total_files = len(file_batch)
        if total_files == 0:
            return

        file_weight = 90.0 / total_files

        for idx, file_info in enumerate(file_batch, start=1):
            file_path = file_info["path"]
            filename = file_info["filename"]
            file_base_progress = (idx - 1) * file_weight

            def update_job_progress(sub_step_desc: str, sub_percent: float):
                calculated_pct = int(file_base_progress + (file_weight * sub_percent))
                job = (
                    db.query(IngestionJob).filter(IngestionJob.job_id == job_id).first()
                )
                if job:
                    job.step = f"[{idx}/{total_files}] {filename}: {sub_step_desc}"
                    job.progress = calculated_pct
                    db.commit()

            try:
                update_job_progress("Reading file...", 0.05)

                with open(file_path, "rb") as f:
                    file_bytes = f.read()

                # Stage 1: Parse
                chunks = parser_engine.parse_file(
                    file_bytes,
                    filename,
                    db=db,
                    chunk_size=chunk_size,
                    chunk_overlap=chunk_overlap,
                    on_progress=lambda desc, pct: update_job_progress(
                        f"Parsing - {desc}", 0.05 + (pct * 0.45)
                    ),
                )

                # Stage 2: Embed & Insert into Vector DB
                if chunks:
                    db_engine.insert_document_chunks(
                        chunks,
                        filename,
                        on_progress=lambda desc, pct: update_job_progress(
                            f"Vectorizing - {desc}", 0.50 + (pct * 0.45)
                        ),
                    )

            except Exception as e:
                # Log error and continue with the next file instead of aborting all files
                failed_files.append(f"{filename} ({e!s})")
                logger.error(f"Error processing {filename}: {e!s}")

            # finally:
            #     if os.path.exists(file_path):
            #         os.remove(file_path)

            update_job_progress("File finished", 1.0)

        # Final Batch Status Summary
        job = db.query(IngestionJob).filter(IngestionJob.job_id == job_id).first()
        if job:
            if failed_files:
                # If some files failed but others passed
                job.status = (
                    "completed" if len(failed_files) < total_files else "failed"
                )
                job.step = (
                    f"Ingestion finished. Failed files: {', '.join(failed_files)}"
                )
                job.progress = 100
            else:
                job.status = "completed"
                job.step = "All files ingested successfully"
                job.progress = 100
            db.commit()

    finally:
        db.close()


